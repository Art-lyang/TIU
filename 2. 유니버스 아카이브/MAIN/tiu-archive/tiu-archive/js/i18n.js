  const STORAGE_KEY  = 'tiu-lang';
  const DEFAULT_LANG = 'ko';
  const SUPPORTED    = ['ko', 'en', 'ja'];

  function applyLang(lang) {
    if (!SUPPORTED.includes(lang)) lang = DEFAULT_LANG;
    const dict = DICT[lang];
    document.documentElement.lang = lang;

    /* 텍스트 컨텐츠 */
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const v = dict[el.dataset.i18n];
      if (v !== undefined) el.textContent = v;
    });

    /* HTML 컨텐츠 (br 등 허용) */
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const v = dict[el.dataset.i18nHtml];
      if (v !== undefined) el.innerHTML = v;
    });

    /* aria-label 같은 속성 번역 */
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const v = dict[el.dataset.i18nAria];
      if (v !== undefined) el.setAttribute('aria-label', v);
    });

    /* 토글 버튼 활성 상태 */
    document.querySelectorAll('[data-lang-btn]').forEach(btn => {
      btn.classList.toggle('is-active', btn.dataset.langBtn === lang);
    });

    document.dispatchEvent(new CustomEvent('tiu:langchange', { detail: { lang } }));
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* private mode 등 */ }
  }

  function init() {
    document.querySelectorAll('[data-lang-btn]').forEach(btn => {
      btn.addEventListener('click', () => applyLang(btn.dataset.langBtn));
    });

    let saved = null;
    try { saved = localStorage.getItem(STORAGE_KEY); } catch (e) {}
    applyLang(saved || DEFAULT_LANG);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
