  function normalizeLang(lang) {
    return DICT[lang] ? lang : 'ko';
  }

  function setText(selector, dict, attr, setter) {
    document.querySelectorAll(selector).forEach((node) => {
      const key = node.getAttribute(attr);
      if (!key || dict[key] === undefined) return;
      setter(node, dict[key]);
    });
  }

  function applyLanguage(lang) {
    const nextLang = normalizeLang(lang);
    const dict = DICT[nextLang];
    document.documentElement.lang = nextLang;
    try { localStorage.setItem('tiu-lang', nextLang); } catch (error) {}

    setText('[data-i18n]', dict, 'data-i18n', (node, value) => { node.textContent = value; });
    setText('[data-i18n-html]', dict, 'data-i18n-html', (node, value) => { node.innerHTML = value; });
    setText('[data-i18n-aria]', dict, 'data-i18n-aria', (node, value) => { node.setAttribute('aria-label', value); });

    document.querySelectorAll('[data-lang-btn]').forEach((button) => {
      const active = button.dataset.langBtn === nextLang;
      button.classList.toggle('is-active', active);
      button.setAttribute('aria-pressed', active ? 'true' : 'false');
    });

    document.dispatchEvent(new CustomEvent('tiu:langchange', { detail: { lang: nextLang } }));
  }

  function initialLang() {
    try {
      const saved = localStorage.getItem('tiu-lang');
      if (saved && DICT[saved]) return saved;
    } catch (error) {}
    const attr = document.documentElement.lang;
    return normalizeLang(attr || 'ko');
  }

  document.addEventListener('DOMContentLoaded', () => {
    document.querySelectorAll('[data-lang-btn]').forEach((button) => {
      button.addEventListener('click', () => applyLanguage(button.dataset.langBtn));
    });
    applyLanguage(initialLang());
  });
